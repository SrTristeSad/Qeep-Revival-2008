package.path='server/lib/?.lua;client/lib/?.lua;'..package.path
local store=require('social_store')
local root='server/data/phase13_store_test.db'
os.remove(root);os.remove(root..'.tmp')
local checks=0
local function ck(cond,msg) assert(cond,msg or ('assertion '..(checks+1)));checks=checks+1 end
local db=assert(store.new(root))
ck(not store.is_contact(db,'alice','beatriz'))
ck(not store.send(db,'alice','beatriz','Sem permissão'))
ck(store.request(db,'alice','beatriz'))
ck(not store.request(db,'alice','beatriz'),'duplicate request rejected')
ck(not store.request(db,'beatriz','alice'),'reverse request rejected')
local contacts,pending=store.list(db,'beatriz')
ck(#contacts==0 and pending[1]=='alice')
ck(store.answer(db,'beatriz','alice',true))
ck(store.is_contact(db,'alice','beatriz'))
ck(not store.answer(db,'beatriz','alice',true),'cannot approve twice')
ck(not store.send(db,'alice','intruso','no contact'))
ck(not store.send(db,'alice','beatriz','\0bad'))
ck(not store.send(db,'alice','beatriz',string.rep('X',241)))
local seq=assert(store.send(db,'alice','beatriz','Olá <Bia> & 🐱'))
ck(seq==1)
ck(assert(store.send(db,'beatriz','alice','Tudo bem?'))==2)
local msgs,rev=store.thread(db,'alice','beatriz')
ck(rev==2 and #msgs==2)
ck(msgs[1].text=='Olá <Bia> & 🐱')
local again=assert(store.new(root))
ck(store.is_contact(again,'alice','beatriz'),'contact persisted')
local restored,rrev=store.thread(again,'beatriz','alice')
ck(rrev==2 and restored[2].text=='Tudo bem?','messages persisted')
ck(assert(store.send(again,'alice','beatriz','Terceira'))==3,'sequence persisted')
ck(store.request(again,'beatriz','carla'))
ck(store.answer(again,'carla','beatriz',false))
ck(not store.is_contact(again,'beatriz','carla'),'rejected is not contact')
local f=assert(io.open(root,'wb'));assert(f:write('INVALID!\n'));f:close()
local damaged,errorMessage=store.new(root)
ck(damaged==nil and errorMessage~=nil,'corrupt files cannot silently reset')
os.remove(root);os.remove(root..'.tmp')
print(('OK: %d durable social store checks'):format(checks))
