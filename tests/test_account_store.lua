-- Local persistent account store test; NEVER uses a real user's credentials.
package.path='server/lib/?.lua;client/lib/?.lua;'..package.path
local sha=require('sha256')
local accounts=require('account_store')
local checks=0
local function ck(b,what) assert(b,what or ('check '..(checks+1)));checks=checks+1 end
ck(sha.hex('')=='e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855','sha empty')
ck(sha.hex('abc')=='ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad','sha abc')
ck(sha.hex(string.rep('a',1000))=='41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3','sha long')
local path='server/data/phase12_unit_test.db'
os.remove(path);os.remove(path..'.tmp')
local db=assert(accounts.new(path))
ck(not accounts.allowed('../bad'),'invalid name')
ck(not accounts.allowed('ABCD'),'uppercase not canonical')
ck(accounts.allowed('test_abc1'),'valid name')
ck(not accounts.verify(db,'test_abc1','secret'),'unknown user')
local code=assert(accounts.register(db,'test_abc1'))
ck(#code==48 and code:match('^[0-9a-f]+$'),'code format')
ck(accounts.verify(db,'test_abc1',code),'verify registered')
ck(not accounts.verify(db,'test_abc1','somepassword'),'reject password')
ck(not accounts.register(db,'test_abc1'),'duplicate account')
local file=assert(io.open(path,'rb'))
local saved=file:read('*a');file:close()
ck(saved:find('QEEP_REVIVAL_ACCOUNTS_1',1,true)~=nil)
ck(not saved:find(code,1,true),'plaintext secret must not be on disk')
ck(saved:find('test_abc1',1,true)~=nil)
local reopened=assert(accounts.new(path))
ck(accounts.verify(reopened,'test_abc1',code),'persists after reload')
ck(not accounts.verify(reopened,'test_abc1',code:sub(1,47)..(code:sub(48)=='a' and 'b' or 'a')))
local other=assert(accounts.register(reopened,'user_2'))
ck(other~=code)
local reloaded=assert(accounts.new(path))
ck(accounts.verify(reloaded,'test_abc1',code))
ck(accounts.verify(reloaded,'user_2',other))
local bad=assert(io.open(path,'wb'))
bad:write('INVALID FILE\n');bad:close()
local broken,err=accounts.new(path)
ck(not broken and err:find('header'),'fail closed on corrupt data')
os.remove(path);os.remove(path..'.tmp')
print(('OK: %d account-store checks'):format(checks))
