package.path = 'client/?.lua;client/lib/?.lua;' .. package.path
local jcl = require('jcl')
local view = require('jcl_view')
local file = assert(io.open('client/fixtures/lab.xml', 'rb'))
local source = file:read('*a'); file:close()
local n = 0
local function eq(a,b)
  assert(a == b, tostring(a)..' ~= '..tostring(b))
  n = n + 1
end
local function bad(xml)
  local ok = pcall(jcl.parse,xml)
  eq(ok,false)
end
local data = jcl.parse(source)
eq(#data.forms,3)
eq(data.forms[1].id,'index')
eq(data.forms[2].title,'Campos JCL')
eq(data.forms[1].items[4].kind,'a')
eq(data.forms[2].items[1].length,30)
eq(data.forms[2].items[3].options[2].value,'2')
local model = view.new(data)
eq(model.selected,4)
eq(view.activate(model),'#fields')
eq(view.next_form(model,'fields'),true)
eq(view.item(model).kind,'input')
eq(view.activate(model),'editing')
view.text(model,'Alex')
eq(view.item(model).value,'Alex')
view.backspace(model)
eq(view.item(model).value,'Ale')
view.cancel_edit(model)
eq(view.move(model,1),true)
eq(view.item(model).kind,'textarea')
eq(view.move(model,1),true)
eq(view.item(model).kind,'select')
eq(view.item(model).selected,1)
eq(view.activate(model),'selected')
eq(view.item(model).selected,2)
eq(view.next_form(model,'unknown'),false)
local escaped = jcl.parse('<jcl><form id="a"><p label="A &amp; B &lt; C &#x1F600;"/><textarea>&quot;Hi&quot;</textarea></form></jcl>')
eq(escaped.forms[1].items[1].label,'A & B < C 😀')
eq(escaped.forms[1].items[2].value,'"Hi"')
local prop = jcl.parse('<jcl base="/foo"><prop n="v" v="ok"/><form title="test"><layout><button label="go" href="#foo"/></layout></form></jcl>')
eq(prop.base,'/foo')
eq(prop.props.v,'ok')
eq(prop.forms[1].items[1].href,'#foo')
bad('<!DOCTYPE jcl [<!ENTITY x SYSTEM "file:///etc/passwd">]><jcl><form/></jcl>')
bad('<jcl><form><input></form></jcl>')
bad('<jcl><form/><form id="x" bad=x/></jcl>')
bad('<html><form/></html>')
bad('<jcl><form><p label="&unknown;"/></form></jcl>')
bad('<jcl><form><p label="&#xD800;"/></form></jcl>')
bad('<jcl><form id="x" id="y"/></jcl>')
bad('<jcl><form/></jcl><jcl/>')
bad('<jcl>'..string.rep('<layout>',35)..'<form/>'..string.rep('</layout>',35)..'</jcl>')
bad('<jcl>'..string.rep('<form/>',513)..'</jcl>')
bad(string.rep(' ',262145))
print(('OK: %d Lua JCL checks'):format(n))
