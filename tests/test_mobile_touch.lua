package.path='client/?.lua;client/lib/?.lua;'..package.path
local touch = require('lib.mobile_touch')
local count=0
local function check(v) assert(v,'mobile gesture checkpoint '..(count+1));count=count+1 end
local s=touch.new()
check(touch.press(s,1,20,30,true,2))
check(not touch.press(s,2,30,40,true,2))
check(touch.move(s,2,70,80,2)==0)
check(touch.move(s,1,24,33,2)==0)
check(touch.release(s,1,24,33))
check(touch.press(s,1,20,30,true,2))
check(touch.move(s,1,20,40,2)==0)
check(touch.move(s,1,20,52,2)==-6)
check(touch.move(s,1,20,62,2)==-5)
check(not touch.release(s,1,20,62))
check(touch.press(s,3,20,300,false,2))
check(touch.move(s,3,20,250,2)==0)
check(not touch.release(s,3,20,250))
check(touch.press(s,4,0,0,true,3))
touch.reset(s)
check(not touch.release(s,4,0,0))
check(touch.press(s,5,0,0,true,1))
check(touch.move(s,5,100,100,1)==-100)
check(not touch.release(s,5,100,100))
print(('OK: %d mobile touch checks'):format(count))
