#!/usr/bin/env python3
"""Exercise real Android emulator taps after android_smoke.py validated APK startup.

Screenshots and evidence are generated by adb, never reconstructed or mocked.
Without OCR, deterministic purple-band geometry and visual state transitions
provide conservative evidence that touch navigation did something meaningful.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import time

from PIL import Image, ImageChops
from android_smoke import DEFAULT_ACTIVITY, DEFAULT_PACKAGE, adb

PURPLE = (125, 20, 125)
MENU_Y, MENU_ROW = 91, 22


def runs(values: list[int]) -> list[tuple[int, int]]:
    result = []
    for i in values:
        if not result or i > result[-1][1] + 1:
            result.append([i, i])
        else:
            result[-1][1] = i
    return [tuple(x) for x in result]


def canvas(image: Image.Image) -> dict:
    """Locate the two solid-purple 25px softkey/header bands of the 240x320 UI."""
    rgb = image.convert('RGB')
    width, height = rgb.size
    probe = max(1, min(width - 1, round(width * 0.005)))
    bands = [b for b in runs([y for y in range(height) if rgb.getpixel((probe,y))==PURPLE])
             if b[1]-b[0]+1 >= 16]
    if len(bands) != 2:
        raise ValueError(f'expected 2 Qeep purple bands, found {bands}')
    top, footer = bands
    scale = (footer[0]-top[0])/295.0
    if scale < 1 or abs((top[1]-top[0]+1)/25-scale)>0.12:
        raise ValueError(f'inconsistent Qeep top band and scale {scale}')
    if abs((footer[1]-footer[0]+1)/25-scale)>0.12:
        raise ValueError('inconsistent footer band height')
    x0 = (width-240*scale)/2
    coverage = (240*scale)/width
    return {'x':x0,'y':top[0],'scale':scale,'width_coverage':coverage,
            'top':list(top),'footer':list(footer),'screen':list(rgb.size)}


def logical_point(geometry: dict, x: float, y: float) -> tuple[int,int]:
    return round(geometry['x']+x*geometry['scale']), round(geometry['y']+y*geometry['scale'])


def pixels_changed(left: Image.Image, right: Image.Image, geometry: dict) -> float:
    """Compare only the application's content, excluding clock/status/navigation bars."""
    if left.size != right.size:
        raise ValueError('inconsistent emulator screenshot sizes')
    x1,y1=logical_point(geometry,10,32)
    x2,y2=logical_point(geometry,230,292)
    a=left.convert('RGB').crop((x1,y1,x2,y2))
    b=right.convert('RGB').crop((x1,y1,x2,y2))
    diff=ImageChops.difference(a,b).convert('L').point(lambda p: 255 if p>=25 else 0)
    hist=diff.histogram()
    return (sum(hist[1:])/max(1,a.width*a.height))


def screenshot(output: Path, name: str) -> Image.Image:
    data=adb('exec-out','screencap','-p',binary=True)
    if not data.startswith(b'\x89PNG\r\n\x1a\n'):
        raise RuntimeError('adb did not return PNG')
    target=output/(name+'.png')
    target.write_bytes(data)
    with Image.open(target) as image:
        image.load()
        return image.copy()


def tap(geom: dict, x: float, y: float) -> None:
    px,py=logical_point(geom,x,y)
    adb('shell','input','tap',str(px),str(py),timeout=20)
    time.sleep(1.4)


def alive(package: str) -> bool:
    return bool(adb('shell','pidof','-s',package).strip())


def navigate(output: Path, package: str, activity: str) -> bool:
    output.mkdir(parents=True,exist_ok=True)
    checks: list[dict] = []
    report = {'package':package,'activity':activity,'passed':False,'checks':checks}
    try:
        if not alive(package):
            raise RuntimeError('Qeep process not running after startup smoke')
        menu=screenshot(output,'01-menu')
        geom=canvas(menu)
        report['geometry']=geom
        checks.append({'name':'mobile_full_width','passed':geom['width_coverage']>=0.96,
                       'coverage':round(geom['width_coverage'],5)})
        if not checks[-1]['passed']:
            raise AssertionError('mobile screen remains letterboxed horizontally')
        # About is entirely local: no login, remote server or saved changes.
        tap(geom,120,MENU_Y+5*MENU_ROW+MENU_ROW/2)
        about=screenshot(output,'02-about')
        d1=pixels_changed(menu,about,geom)
        checks.append({'name':'tap_open_about','passed':d1>=0.035,'fraction_changed':round(d1,5)})
        if not checks[-1]['passed']:raise AssertionError('About touch did not change screen')
        tap(geom,120,307)  # the mobile 'Voltar' footer
        back=screenshot(output,'03-menu-return')
        d2=pixels_changed(about,back,geom)
        checks.append({'name':'touch_back_to_menu','passed':d2>=0.035,'fraction_changed':round(d2,5)})
        if not checks[-1]['passed']:raise AssertionError('Back touch did not change screen')
        # Offline JCL: verify a second non-network screen responds to touch.
        tap(geom,120,MENU_Y+MENU_ROW/2)
        offline=screenshot(output,'04-offline-jcl')
        d3=pixels_changed(back,offline,geom)
        checks.append({'name':'tap_open_offline_jcl','passed':d3>=0.035,'fraction_changed':round(d3,5)})
        if not checks[-1]['passed']:raise AssertionError('Offline JCL touch did not change screen')
        # Exercise an actual JCL form transition and the clickable left
        # softkey. This is stronger than testing only root menu navigation.
        tap(geom,120,175)  # first '#fields' link in the offline fixture
        fields=screenshot(output,'05-fields')
        d4=pixels_changed(offline,fields,geom)
        checks.append({'name':'tap_jcl_link','passed':d4>=0.035,
                       'fraction_changed':round(d4,5)})
        if not checks[-1]['passed']:raise AssertionError('JCL link did not change form')
        tap(geom,45,307)  # synthesized 'Voltar' softkey
        returned=screenshot(output,'06-jcl-back')
        d5=pixels_changed(offline,returned,geom)
        checks.append({'name':'tap_jcl_back','passed':d5<0.09,
                       'difference_from_index':round(d5,5)})
        if not checks[-1]['passed']:raise AssertionError('JCL back did not return to index')
        checks.append({'name':'process_still_alive','passed':alive(package)})
        if not checks[-1]['passed']:raise AssertionError('process crashed during touch navigation')
        report['passed']=True
    except Exception as ex:
        report['errors']=[f'{type(ex).__name__}: {ex}']
    finally:
        try:
            (output/'logcat.txt').write_text(adb('logcat','-d','-v','brief',timeout=45),encoding='utf-8')
        except Exception as ex:
            report['logcat_error']=str(ex)[:350]
        (output/'result.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    return report['passed']


def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=Path('android-navigation-results'))
    parser.add_argument('--package',default=DEFAULT_PACKAGE)
    parser.add_argument('--activity',default=DEFAULT_ACTIVITY)
    args=parser.parse_args()
    result=navigate(args.output,args.package,args.activity)
    print('Android navigation:', 'PASS' if result else 'FAIL',args.output)
    return 0 if result else 1


if __name__=='__main__':
    raise SystemExit(main())
